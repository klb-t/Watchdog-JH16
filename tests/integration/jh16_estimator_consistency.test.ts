/**
 * Set-logic consistency of stored JH16 counts (scripts/jh16_estimator_consistency.py):
 * the evidence prepared for the open diagnosis "Zmiana sposobu szacowania przez Google
 * od 2014 r." is regenerated from stored files byte for byte, and the script treats a
 * missing count as missing, never as zero. It decides nothing about that diagnosis.
 */
import { test } from 'node:test';
import * as assert from 'node:assert';
import { spawnSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';

const DIR = 'docs/history/evidence/2026-10-29-jh16-gaps';
const SCRIPT = 'scripts/jh16_estimator_consistency.py';

test('the committed consistency evidence is regenerated byte for byte from stored files', () => {
  const r = spawnSync('bash', [`${DIR}/regenerate.sh`], { encoding: 'utf8', timeout: 60000 });
  assert.strictEqual(r.status, 0, r.stderr);
  assert.strictEqual(r.stdout, fs.readFileSync(`${DIR}/estimator_consistency.json`, 'utf8'));
  const d = JSON.parse(r.stdout);
  assert.strictEqual(d.paper_2014.valid_pairs, 16);
  assert.deepStrictEqual(d.paper_2014.harm_count_above_popularity_count, [], 'the published 2014 counts are coherent');
  const r3 = d.runs_2026.find((x: any) => x.run_id.startsWith('2e701755'));
  assert.deepStrictEqual(r3.harm_count_above_popularity_count, ['butane', 'mephedrone', 'methamphetamine'], 'matches REPORT.md and cross_runs.txt');
  assert.ok(d.runs_2026.every((x: any) => x.violations > 0), 'every stored 2026 run has at least one incoherent pair');
  assert.deepStrictEqual(d.or_decomposition_2026.incoherent, ['alcohol', 'amphetamine', 'buprenorphine', 'mephedrone', 'methadone']);
  for (const x of d.runs_2026) assert.strictEqual(x.file_sha256.length, 64);
});

test('a missing count stays missing and a coherent pair is not a violation', () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'jh16-consistency-'));
  try {
    // Test inputs only: two substances, one with a missing harm count.
    const paper = { substances: [{ canonical: 'a', Ni: 100, Ni_harm: 10 }, { canonical: 'b', Ni: 50, Ni_harm: 5 }] };
    const exp = { run_id: 'r-test', observations: [
      { entity_id: 'a', query_role: 'popularity', is_missing: false, value_numeric: 2000 },
      { entity_id: 'a', query_role: 'harm', is_missing: false, value_numeric: 3000 },
      { entity_id: 'b', query_role: 'popularity', is_missing: false, value_numeric: 2000 },
      { entity_id: 'b', query_role: 'harm', is_missing: true, value_numeric: null }] };
    fs.writeFileSync(path.join(tmp, 'paper.json'), JSON.stringify(paper));
    fs.writeFileSync(path.join(tmp, 'export.json'), JSON.stringify(exp));
    const r = spawnSync('python3', ['-I', path.resolve(SCRIPT), '--root', tmp, '--paper', path.join(tmp, 'paper.json'), '--export', `t=${path.join(tmp, 'export.json')}`], { encoding: 'utf8', timeout: 30000 });
    assert.strictEqual(r.status, 0, r.stderr);
    const d = JSON.parse(r.stdout), run = d.runs_2026[0];
    assert.strictEqual(run.valid_pairs, 1, 'the pair with a missing count is not counted as a pair');
    assert.deepStrictEqual(run.missing_counts, ['b/harm']);
    assert.deepStrictEqual(run.harm_count_above_popularity_count, ['a']);
    assert.strictEqual(d.paper_2014.violations, 0);
    assert.strictEqual(d.exploratory_probability.pooled_rate_2026, 1);
  } finally { fs.rmSync(tmp, { recursive: true, force: true }); }
});
