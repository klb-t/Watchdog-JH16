/**
 * E3.5 first package: the SQLite → PostgreSQL migration translation. Offline;
 * the real-server check is scripts/pg_portability_probe.ts (evidence in
 * docs/architecture/E3_5_POSTGRES_DESIGN.md).
 */
import { test } from 'node:test';
import * as assert from 'node:assert';
import { MIGRATIONS } from '../../backend/watchdog_api/db/migrations';
import { splitStatements, translateStatement } from '../../backend/watchdog_api/db/postgres_dialect';

test('comments with apostrophes and semicolons do not split statements', () => {
  const s = splitStatements("-- it's one; not two\nCREATE TABLE a (x TEXT DEFAULT ';');\nCREATE TABLE b (y TEXT);");
  assert.deepStrictEqual(s, ["CREATE TABLE a (x TEXT DEFAULT ';');", 'CREATE TABLE b (y TEXT);']);
});

test('a WORM trigger becomes a plpgsql function and keeps its message and column list', () => {
  const t = translateStatement("CREATE TRIGGER p_immutable BEFORE UPDATE OF a,b ON p BEGIN SELECT RAISE(ABORT, 'WORM p'); END;");
  assert.strictEqual(t.manual, null);
  assert.match(t.postgres[0], /RAISE EXCEPTION '%', 'WORM p'; RETURN NEW;/);
  assert.match(t.postgres[1], /^CREATE TRIGGER p_immutable BEFORE UPDATE OF a,b ON p FOR EACH ROW EXECUTE FUNCTION wd_trg_p_immutable\(\)$/);
});

test('a WHEN with a subquery moves into the function body; a plain WHEN stays', () => {
  const sub = translateStatement("CREATE TRIGGER r_no_delete BEFORE DELETE ON r FOR EACH ROW WHEN EXISTS(SELECT 1 FROM o WHERE o.r=OLD.id) BEGIN SELECT RAISE(ABORT, 'kept'); END;");
  assert.match(sub.postgres[0], /IF \(EXISTS\(SELECT 1 FROM o WHERE o\.r=OLD\.id\)\) THEN RAISE EXCEPTION '%', 'kept'; END IF; RETURN OLD;/);
  assert.ok(!/WHEN/.test(sub.postgres[1]));
  const plain = translateStatement("CREATE TRIGGER q BEFORE UPDATE ON q FOR EACH ROW WHEN OLD.body_json IS NOT NULL BEGIN SELECT RAISE(ABORT, 'x'); END;");
  assert.match(plain.postgres[1], /WHEN \(OLD\.body_json IS NOT NULL\)/);
});

test('column and insert rules', () => {
  assert.match(translateStatement('CREATE TABLE e (sequence INTEGER PRIMARY KEY AUTOINCREMENT, b BLOB) STRICT;').postgres[0],
    /^CREATE TABLE e \(sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, b BYTEA\)$/);
  assert.strictEqual(translateStatement("INSERT OR IGNORE INTO roles (id) VALUES ('v');").postgres[0], "INSERT INTO roles (id) VALUES ('v') ON CONFLICT DO NOTHING");
  assert.strictEqual(translateStatement('INSERT OR REPLACE INTO t VALUES (1);').manual, 'INSERT OR REPLACE needs a conflict target');
});

test('every shipped migration translates without a manual step and keeps all 51 triggers', () => {
  let triggers = 0;
  for (const m of MIGRATIONS) for (const stmt of splitStatements(m.sql)) {
    const t = translateStatement(stmt);
    assert.strictEqual(t.manual, null, `${m.id}: ${t.manual}`);
    triggers += t.postgres.filter(s => /^CREATE TRIGGER/.test(s)).length;
  }
  assert.strictEqual(triggers, 51);
});

test('WATCHDOG_DB_BACKEND: sqlite works, postgres is refused as not implemented, anything else is an error', async () => {
  const { resolveDbBackend } = await import('../../backend/watchdog_api/db/backend_setting');
  assert.strictEqual(resolveDbBackend({}), 'sqlite');
  assert.strictEqual(resolveDbBackend({ WATCHDOG_DB_BACKEND: 'SQLite' }), 'sqlite');
  assert.throws(() => resolveDbBackend({ WATCHDOG_DB_BACKEND: 'postgres' }), /NOT_IMPLEMENTED|not implemented/);
  assert.throws(() => resolveDbBackend({ WATCHDOG_DB_BACKEND: 'mysql' }), /must be 'sqlite' or 'postgres'/);
});
