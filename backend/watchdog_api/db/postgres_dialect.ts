/**
 * E3.5 (first package): mechanical translation of WatchDog's SQLite migrations
 * to PostgreSQL. Used by scripts/pg_portability_probe.ts to measure, against a
 * real server, which parts of the schema port as written. It is not yet a
 * runtime backend: the repositories still use the synchronous SQLite API.
 * Every rule is listed here so a result can be read against it.
 */

export interface TranslatedStatement { sqlite: string; postgres: string[]; rules: string[]; manual: string | null }

/**
 * Splits a migration into statements, keeping CREATE TRIGGER … END; together.
 * Line comments are dropped: they hold apostrophes and semicolons in prose.
 */
export function splitStatements(sql: string): string[] {
  const out: string[] = []; let buf = '', inTrigger = false, quote: string | null = null;
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];
    if (!quote && c === '-' && sql[i + 1] === '-') { const end = sql.indexOf('\n', i); i = end < 0 ? sql.length : end - 1; continue; }
    buf += c;
    if (quote) { if (c === quote) quote = null; continue; }
    if (c === "'" || c === '"') { quote = c; continue; }
    if (!inTrigger && /CREATE\s+TRIGGER\s*$/i.test(buf)) inTrigger = true;
    if (c === ';') {
      if (inTrigger && !/\bEND\s*;$/i.test(buf.trimEnd())) continue;
      if (buf.trim() !== ';') out.push(buf.trim()); buf = ''; inTrigger = false;
    }
  }
  if (buf.trim()) out.push(buf.trim());
  return out;
}

const TRIGGER = /^CREATE\s+TRIGGER\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)\s+(BEFORE|AFTER)\s+(INSERT|DELETE|UPDATE(?:\s+OF\s+[\w\s,]+?)?)\s+ON\s+(\w+)\s+(?:FOR\s+EACH\s+ROW\s+)?(?:WHEN\s+([\s\S]+?)\s+)?BEGIN\s+([\s\S]*?)\s*END\s*;?$/i;
const ABORT_ONLY = /^SELECT\s+RAISE\s*\(\s*ABORT\s*,\s*'((?:[^']|'')*)'\s*\)\s*;?$/i;
const CONDITIONAL_ABORT = /^SELECT\s+RAISE\s*\(\s*ABORT\s*,\s*'((?:[^']|'')*)'\s*\)\s+WHERE\s+([\s\S]+?);?$/i;

export function translateStatement(stmt: string): TranslatedStatement {
  const rules: string[] = [];
  const t = TRIGGER.exec(stmt.trim());
  if (t) {
    const [, name, timing, event, table, when, bodyRaw] = t, body = bodyRaw.trim();
    const abort = ABORT_ONLY.exec(body), conditional = CONDITIONAL_ABORT.exec(body);
    if (!abort && !conditional) return { sqlite: stmt, postgres: [], rules: ['trigger'], manual: `trigger ${name}: body is not a single RAISE(ABORT): ${body.slice(0, 120)}` };
    const message = (abort ?? conditional)![1];
    // PostgreSQL refuses a subquery in a trigger's WHEN, so such a guard moves into the body.
    const movedWhen = when && /\bSELECT\b/i.test(when) ? when : null;
    const guard = [movedWhen, conditional ? conditional[2] : null].filter(Boolean).map(g => `(${g})`).join(' AND ') || null;
    if (movedWhen) rules.push('WHEN with subquery → guard in function body');
    const fn = `wd_trg_${name}`;
    const raise = guard ? `IF ${guard} THEN RAISE EXCEPTION '%', '${message}'; END IF;` : `RAISE EXCEPTION '%', '${message}';`;
    rules.push(`trigger → plpgsql function ${fn}${guard ? ' (conditional)' : ''}`);
    const ret = /DELETE/i.test(event) ? 'OLD' : 'NEW';
    return { sqlite: stmt, rules, manual: null, postgres: [
      `CREATE OR REPLACE FUNCTION ${fn}() RETURNS trigger LANGUAGE plpgsql AS $wd$ BEGIN ${raise} RETURN ${ret}; END $wd$`,
      `CREATE TRIGGER ${name} ${timing} ${event.replace(/\s+/g, ' ')} ON ${table} FOR EACH ROW${when && !movedWhen ? ` WHEN (${when})` : ''} EXECUTE FUNCTION ${fn}()`] };
  }
  let s = stmt.trim().replace(/;$/, '');
  const apply = (re: RegExp, to: string, rule: string) => { if (re.test(s)) { s = s.replace(re, to); rules.push(rule); } };
  apply(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 'AUTOINCREMENT → identity');
  apply(/\bBLOB\b/gi, 'BYTEA', 'BLOB → BYTEA');
  apply(/\)\s*STRICT\s*$/i, ')', 'STRICT dropped (PostgreSQL is typed)');
  apply(/json_valid\(\s*(\w+)\s*\)/gi, '($1::jsonb IS NOT NULL)', 'json_valid → jsonb cast');
  apply(/datetime\(\s*'now'\s*\)/gi, `to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')`, "datetime('now') → now()");
  if (/^INSERT\s+OR\s+IGNORE\s+INTO/i.test(s)) { s = s.replace(/^INSERT\s+OR\s+IGNORE\s+INTO/i, 'INSERT INTO') + ' ON CONFLICT DO NOTHING'; rules.push('INSERT OR IGNORE → ON CONFLICT DO NOTHING'); }
  if (/^INSERT\s+OR\s+REPLACE/i.test(s)) return { sqlite: stmt, postgres: [], rules, manual: 'INSERT OR REPLACE needs a conflict target' };
  if (/^PRAGMA\b/i.test(s)) return { sqlite: stmt, postgres: [], rules: ['PRAGMA dropped'], manual: null };
  return { sqlite: stmt, postgres: [s], rules, manual: null };
}
